// @effect-diagnostics nodeBuiltinImport:off globalConsole:off - runs from a bare checkout, before any install, so it has only Node built-ins.
// fork: only the fork's own workflows run here (see FORK.md). Every upstream
// workflow keeps its jobs, which upstream's tests and knip read, but its
// triggers are commented out. Upstream's CI needs Blacksmith runners, which a
// fork cannot use, so the fork runs it from generated copies on GitHub-hosted
// runners. The sync script reruns this after every rebase; edit this file,
// never its output. Node built-ins only.
import * as NodeFS from "node:fs";
import * as NodePath from "node:path";

/** The workflows that run on the fork. Every other workflow file is upstream's, with its triggers commented out. */
export const RUNNING_WORKFLOWS: ReadonlySet<string> = new Set([
  "fork-ci.yml",
  "fork-release.yml",
  "fork-windows-tests.yml",
  // Upstream's packaging, which fork-release.yml calls.
  "release-desktop.yml",
]);

const FORK_CI_TRIGGERS = [
  "on:",
  "  pull_request:",
  "    branches: [fork/main]",
  "  push:",
  '    branches: ["sync/**"]',
  "  workflow_call:",
  "  workflow_dispatch:",
];

export const FORK_WORKFLOWS = [
  { source: "ci.yml", target: "fork-ci.yml", name: "Fork CI", triggers: FORK_CI_TRIGGERS },
  { source: "windows-tests.yml", target: "fork-windows-tests.yml", name: "Fork Windows Tests" },
] as const;

const INERT_NOTE =
  "  # fork: upstream's triggers, commented out so this never runs on the fork (see FORK.md):";
// Nothing calls it, and a workflow needs at least one trigger.
const INERT_TRIGGER = "  workflow_call:";

// GitHub's free runners have about half the cores of upstream's.
const TIMEOUT_FACTOR = 3;

/** The top-level `on:` block's line range, through its last indented line. */
function triggerBlock(lines: ReadonlyArray<string>, name: string) {
  const starts = lines.flatMap((line, index) => (/^["']?on["']?:/.test(line) ? [index] : []));
  if (starts.length !== 1 || lines[starts[0]!] !== "on:") {
    throw new Error(
      `${name} needs exactly one top-level on: block, with its triggers on the lines below it`,
    );
  }
  const start = starts[0]!;
  let end = start + 1;
  for (let index = start + 1; index < lines.length; index++) {
    const line = lines[index]!;
    if (/^\s/.test(line) && line.trim() !== "") end = index + 1;
    else if (line.trim() !== "" && !line.startsWith("#")) break;
  }
  return { start, end };
}

function withTriggers(
  text: string,
  name: string,
  triggers: (block: Array<string>) => Array<string>,
) {
  const lines = text.split("\n");
  const { start, end } = triggerBlock(lines, name);
  return [...lines.slice(0, start), ...triggers(lines.slice(start, end)), ...lines.slice(end)].join(
    "\n",
  );
}

export function isInertWorkflow(text: string): boolean {
  try {
    const lines = text.split("\n");
    const { start, end } = triggerBlock(lines, "workflow");
    const block = lines.slice(start + 1, end);
    return (
      block[0] === INERT_NOTE &&
      block.at(-1) === INERT_TRIGGER &&
      block.slice(1, -1).every((line) => /^ {2}#( .*)?$/.test(line))
    );
  } catch {
    return false;
  }
}

/** Upstream's `on:` block, from either upstream's file or the fork's inert copy of it. */
function upstreamTriggers(block: Array<string>): Array<string> {
  if (!isInertWorkflow(block.join("\n"))) return block;
  return ["on:", ...block.slice(2, -1).map((line) => (line === "  #" ? "" : `  ${line.slice(4)}`))];
}

export function inertWorkflow(text: string, name: string): string {
  if (isInertWorkflow(text)) return text;
  return withTriggers(text, name, (block) => {
    const commented = block.slice(1).map((line) => {
      if (line.trim() === "") return "  #";
      if (!line.startsWith("  "))
        throw new Error(`${name}'s on: block is not indented by two spaces`);
      return `  # ${line.slice(2)}`;
    });
    return ["on:", INERT_NOTE, ...commented, INERT_TRIGGER];
  });
}

export function forkWorkflow(sourceText: string, spec: (typeof FORK_WORKFLOWS)[number]): string {
  const text = withTriggers(sourceText, spec.source, (block) =>
    "triggers" in spec ? [...spec.triggers] : upstreamTriggers(block),
  )
    .replace(/^name: .*$/m, `name: ${spec.name}`)
    .replace(/^(\s*)timeout-minutes: (\d+)$/gm, (_, indent: string, minutes: string) => {
      return `${indent}timeout-minutes: ${Number(minutes) * TIMEOUT_FACTOR}`;
    })
    .replace(/blacksmith-\d+vcpu-ubuntu-(\d\d)(\d\d)(-arm)?/g, "ubuntu-$1.$2$3")
    .replace(/blacksmith-\d+vcpu-macos-(\d+)/g, "macos-$1")
    .replace(/blacksmith-\d+vcpu-windows-(\d+)/g, "windows-$1");
  const leftover = /^\s*runs-on:.*blacksmith.*$/m.exec(text);
  if (leftover) {
    throw new Error(`${spec.source} uses a runner this script cannot map: ${leftover[0].trim()}`);
  }
  return `# Generated by scripts/fork/ci-workflows.ts from ${spec.source}. Do not edit; run
# node scripts/fork/ci-workflows.ts to regenerate.
${text}`;
}

/** Rewrites the workflows that changed and returns their repository paths. */
export function regenerateWorkflows(repoRoot: string): Array<string> {
  const workflowsDir = NodePath.join(repoRoot, ".github/workflows");
  const read = (file: string) => NodeFS.readFileSync(NodePath.join(workflowsDir, file), "utf8");
  const changed: Array<string> = [];
  const write = (file: string, next: string) => {
    const path = NodePath.join(workflowsDir, file);
    if (NodeFS.existsSync(path) && read(file) === next) return;
    NodeFS.writeFileSync(path, next);
    changed.push(NodePath.posix.join(".github/workflows", file));
  };
  for (const spec of FORK_WORKFLOWS) write(spec.target, forkWorkflow(read(spec.source), spec));
  for (const file of NodeFS.readdirSync(workflowsDir).toSorted()) {
    if (/\.ya?ml$/.test(file) && !RUNNING_WORKFLOWS.has(file)) {
      write(file, inertWorkflow(read(file), file));
    }
  }
  return changed;
}

if (import.meta.main) {
  const changed = regenerateWorkflows(NodePath.join(import.meta.dirname, "../.."));
  console.log(changed.length === 0 ? "Workflows are up to date." : changed.join("\n"));
}
